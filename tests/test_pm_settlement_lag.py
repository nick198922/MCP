def test_settlement_flags() -> None:
    t_obs = 1763658060
    ok = {"outcomePrices": '["1", "0"]', "closedTime": "2025-11-20 19:00:00+00", "umaResolutionStatuses": '["proposed"]'}
    s = settlement(ok, t_obs, 0)
    assert s["paid"] and s["paid_7d"] and not s["nonpay"] and not s["mismatch"] and not s["disputed"]
    assert s["lag_s"] == 1763665200 - t_obs
    wrong = settlement(ok, t_obs, 1)
    assert wrong["mismatch"] and wrong["nonpay"] and not wrong["paid"]
    late = settlement({**ok, "closedTime": "2025-11-28 17:02:00+00"}, t_obs, 0)
    assert late["paid"] and not late["paid_7d"] and late["nonpay"]
    split = settlement({**ok, "outcomePrices": '["0.5", "0.5"]'}, t_obs, 0)
    assert split["nonpay"] and not split["mismatch"]
    disp = settlement({**ok, "umaResolutionStatuses": '["proposed", "disputed", "proposed", "resolved"]'}, t_obs, 0)
    assert disp["disputed"] and disp["n_proposals"] == 2 and disp["paid_7d"]
    no_close = settlement({**ok, "closedTime": None}, t_obs, 0)
    assert no_close["paid"] and no_close["nonpay"]
    # umaEndDate as the settlement time (sensitivity / late-only rule)
    uma = settlement({**ok, "closedTime": "2025-11-28 17:02:00+00", "umaEndDate": "2025-11-20T19:05:00Z"}, t_obs, 0, "umaEndDate")
    assert uma["paid_7d"] and uma["lag_s"] == 1763665500 - t_obs


def test_fee_and_entry_return() -> None:
    assert taker_fee(0.98, 0.0, 1.0) == 0.0
    assert taker_fee(0.5, 0.02, 1.0) == pytest.approx(0.005)
    assert taker_fee(0.5, 0.02, 2.0) == pytest.approx(0.02 * 0.0625)
    # 0.97 + 1 c = 0.98 ask, paid, no hold -> 1/0.98 - 1
    assert entry_return(0.97, paid=True, hold_s=0) == pytest.approx(1 / 0.98 - 1)
    assert entry_return(0.97, paid=False, hold_s=0) == pytest.approx(-1.0)
    # one day at 5 % APR costs 0.05/365
    assert entry_return(0.97, paid=True, hold_s=DAY_S) == pytest.approx(1 / 0.98 - 1 - 0.05 / 365)
    assert entry_return(0.976, paid=True, hold_s=0) is None  # ask 0.986 > 0.985: no entry
    assert entry_return(0.976, paid=True, hold_s=0, max_ask=1.0) == pytest.approx(1 / 0.986 - 1)
    fee = 0.02 * 0.98 * 0.02
    assert entry_return(0.97, paid=True, hold_s=0, fee_rate=0.02, fee_exp=1.0) == pytest.approx(1 / (0.98 + fee) - 1)


def test_gate_decision() -> None:
    nonpay_ok = [False] * 200
    r_ok = [0.01] * 120
    g = gate_decision([0.995] * 70 + [0.99] * 30 + [0.98] * 20, r_ok, nonpay_ok)
    assert g["K1"]["verdict"] == "kill" and g["K1"]["value"] == 0.995 and g["card"] == "rejected"
    g = gate_decision([0.995] * 60 + [0.99] * 40 + [0.98] * 20, r_ok, nonpay_ok)  # median (0.99+0.995)/2
    assert g["K1"]["verdict"] == "pass" and g["K1"]["value"] == pytest.approx(0.9925)
    g = gate_decision([0.97] * 120, r_ok, nonpay_ok)
    assert g["K1"]["verdict"] == "pass" and g["K2"]["verdict"] == "pass" and g["K3"]["verdict"] == "pass"
    assert g["card"] == "forward"
    g = gate_decision([0.97] * 120, [0.002] * 120, nonpay_ok)
    assert g["K2"]["verdict"] == "kill" and g["card"] == "rejected"
    g = gate_decision([0.97] * 120, r_ok, [True] * 3 + [False] * 197)  # 1.5 % > 1 %
    assert g["K3"]["verdict"] == "kill"
    g = gate_decision([0.97] * 120, r_ok, [True] * 2 + [False] * 198)  # exactly 1 % does not kill
    assert g["K3"]["verdict"] == "pass"
    g = gate_decision([0.999] * 99, [0.0] * 29, [True] * 99)
    assert {g[k]["verdict"] for k in ("K1", "K2", "K3")} == {"undecided"} and g["card"] == "forward-undecided"


