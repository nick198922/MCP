def test_offset_audit_rule() -> None:
    def mm(kind: str, var: str, minus: bool, plus: bool) -> dict:
        return {"kind": kind, "variant": var, "by_minus": minus, "by_plus": plus}

    a = offset_audit([mm("above", "closing_1200", False, True)] * 3 + [mm("above", "1200", True, False)] * 2)
    assert a[("above", "closing_1200")]["fix"] == 60  # 3 of 3 explained by +1 min
    assert a[("above", "1200")]["fix"] == 0  # only 2 mismatches
    a = offset_audit([mm("updown", "1200", True, False)] * 2 + [mm("updown", "1200", False, False)] * 2)
    assert a[("updown", "1200")]["fix"] == 0  # 2 of 4 is not MORE than half
    a = offset_audit([mm("updown", "1200", True, True)] * 3)
    assert a[("updown", "1200")]["fix"] == 0  # both neighbours explain equally: ambiguous, no fix
    a = offset_audit([mm("updown", "1200", True, True)] * 3 + [mm("updown", "1200", True, False)])
    assert a[("updown", "1200")]["fix"] == -60


